public class arrays {
    public static void main(String[] args) {
        // Data of same datatype stored in continuous blocks of memory
        // Fast and quick datatype and can access the data stored based on index

        int[] arr = {1,2,3,4,5};

        for(int num:arr){
            System.out.println(num);
        }
        System.out.println(arr[2]);

    }
}
