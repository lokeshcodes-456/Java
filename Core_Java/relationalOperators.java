public class relationalOperators {
    public static void main(String[] args) {
        //Generally there are 7 operators
        /*
        < Less than
        > Greater than
        == Equal to
        = Assign operator
        <= Less than equal to
        >= Greater than equal to
        != Not Equal to
         */

        int a = 7; //Assignment opearator
        int b = 8;
        System.out.println(a<b);
        System.out.println(a>b);
        System.out.println(a==b);
        System.out.println(a<=b);
        System.out.println(a>=b);
        System.out.println(a!=b);

        //Outputs will be give in boolean because of comparisions

    }
}
